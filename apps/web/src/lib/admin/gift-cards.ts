import { GIFT_CARD_MAX_VALUE_MINOR_UNITS } from "@mocha-house/contracts";
import type {
  AdjustGiftCardBalanceRequest,
  AdminGiftCardDetail,
  IssueGiftCardRequest,
  UpdateGiftCardConfigurationRequest,
} from "@mocha-house/contracts";
import type { GiftCardMutationResult } from "@/lib/api-client";
import { formatPrice, parseDollarInput } from "@/lib/money";

// The ONE place the HQ gift-card forms' client-side validation and request
// shaping live (Milestone 7F). The API
// (`/api/v1/admin/gift-cards*`, CORPORATE-only) re-validates everything —
// these helpers just keep the forms honest before they submit.

export const GIFT_CARD_REASON_MAX_LENGTH = 1000;

export type CorrectionDirection = "add" | "deduct";

export type PrepareResult<T> =
  | { ok: true; value: T }
  | { ok: false; error: string };

// --- Issue -----------------------------------------------------------

export function prepareIssue(amountInput: string): PrepareResult<IssueGiftCardRequest> {
  const parsed = parseDollarInput(amountInput);
  if (!parsed.ok) {
    return { ok: false, error: parsed.error };
  }
  if (parsed.cents === null || parsed.cents <= 0) {
    return { ok: false, error: "Enter a gift-card amount greater than $0.00." };
  }
  if (parsed.cents > GIFT_CARD_MAX_VALUE_MINOR_UNITS) {
    return {
      ok: false,
      error: "A gift card cannot be worth more than $2,000.00.",
    };
  }
  return { ok: true, value: { originalValueMinorUnits: parsed.cents } };
}

// --- Manual balance correction ------------------------------------

export interface CorrectionFormValues {
  direction: CorrectionDirection;
  amount: string; // raw dollar text
  reason: string;
}

// `operationKey` is generated by the caller (a UUID) and REUSED across a
// retry of the same submission so a lost-response retry is idempotent.
export function prepareCorrection(
  values: CorrectionFormValues,
  operationKey: string,
): PrepareResult<AdjustGiftCardBalanceRequest> {
  const parsed = parseDollarInput(values.amount);
  if (!parsed.ok) {
    return { ok: false, error: parsed.error };
  }
  if (parsed.cents === null || parsed.cents <= 0) {
    return { ok: false, error: "Enter an amount greater than $0.00." };
  }
  if (parsed.cents > GIFT_CARD_MAX_VALUE_MINOR_UNITS) {
    return { ok: false, error: "That amount is above the $2,000.00 ceiling." };
  }

  const reason = values.reason.trim();
  if (reason.length === 0) {
    return { ok: false, error: "A reason is required." };
  }
  if (reason.length > GIFT_CARD_REASON_MAX_LENGTH) {
    return {
      ok: false,
      error: `Keep the reason under ${GIFT_CARD_REASON_MAX_LENGTH} characters.`,
    };
  }

  const deltaMinorUnits =
    values.direction === "deduct" ? -parsed.cents : parsed.cents;

  return { ok: true, value: { deltaMinorUnits, reason, operationKey } };
}

// Would this correction take the balance outside [0, $2,000.00]? The API
// enforces this authoritatively; the form uses it to warn before submitting.
export function correctionWouldBeOutOfRange(
  currentBalanceMinorUnits: number,
  deltaMinorUnits: number,
): boolean {
  const next = currentBalanceMinorUnits + deltaMinorUnits;
  return next < 0 || next > GIFT_CARD_MAX_VALUE_MINOR_UNITS;
}

// SC0.5c — the API's stable code for an operationKey already applied to a
// DIFFERENT correction (another card, amount, direction or reason).
export const GIFT_CARD_OPERATION_KEY_CONFLICT =
  "GIFT_CARD_OPERATION_KEY_CONFLICT";

// SC0.5d — what the correction form does after a submission's result. Pure,
// so every branch is unit-tested; the form only applies it. It never
// resubmits: the next request only ever comes from the operator.
//
//   success          -> new key (the next correction is a new operation),
//                       inputs cleared, card refreshed.
//   key conflict     -> the key is spent on a correction that is NOT this
//                       one: new key, inputs KEPT, card refreshed so the
//                       ledger shows what was really applied, and the
//                       operator must confirm they reviewed it first.
//   anything else    -> the SAME key and inputs. A network error, timeout or
//   (incl. network,     5xx may have been applied server-side; resubmitting
//    timeout, 5xx)      with the same key is then a safe replay, never a
//                       second correction.
export interface CorrectionStep {
  operationKey: string;
  clearInputs: boolean;
  refresh: boolean;
  reviewRequired: boolean;
  error: string | null;
  notice: string | null;
}

export function correctionStepAfter(
  result: GiftCardMutationResult<AdminGiftCardDetail>,
  currentOperationKey: string,
  newOperationKey: () => string,
): CorrectionStep {
  const keep = {
    operationKey: currentOperationKey,
    clearInputs: false,
    refresh: false,
    reviewRequired: false,
    notice: null,
  };
  switch (result.outcome) {
    case "success":
      return {
        operationKey: newOperationKey(),
        clearInputs: true,
        refresh: true,
        reviewRequired: false,
        error: null,
        notice: `Balance is now ${formatPrice(
          result.data.giftCard.balanceMinorUnits,
          result.data.giftCard.currency,
        )}.`,
      };
    case "conflict":
      if (result.code === GIFT_CARD_OPERATION_KEY_CONFLICT) {
        return {
          operationKey: newOperationKey(),
          clearInputs: false,
          refresh: true,
          reviewRequired: true,
          error: result.message,
          notice: null,
        };
      }
      return { ...keep, error: result.message };
    case "forbidden":
      return {
        ...keep,
        error: "You don't have permission to correct gift-card balances.",
      };
    case "not-found":
      return { ...keep, error: "This gift card no longer exists." };
    default:
      // invalid / error carry a business-safe message.
      return { ...keep, error: result.message };
  }
}

// After a key conflict the operator must confirm they reviewed the refreshed
// balance and ledger — only once the refresh has actually landed — before
// the form will submit again.
export function canSubmitCorrection(state: {
  pending: boolean;
  reviewRequired: boolean;
  reviewed: boolean;
  refreshing: boolean;
}): boolean {
  if (state.pending) {
    return false;
  }
  return !state.reviewRequired || (state.reviewed && !state.refreshing);
}

// --- Configuration ----------------------------------------------

export interface ConfigurationFormValues {
  // One dollar amount per line / entry.
  presetInputs: string[];
  customAmountEnabled: boolean;
}

export function prepareConfiguration(
  values: ConfigurationFormValues,
): PrepareResult<UpdateGiftCardConfigurationRequest> {
  const cleaned = values.presetInputs
    .map((raw) => raw.trim())
    .filter((raw) => raw.length > 0);

  if (cleaned.length === 0) {
    return { ok: false, error: "Add at least one preset amount." };
  }
  if (cleaned.length > 12) {
    return { ok: false, error: "Add at most 12 preset amounts." };
  }

  const seen = new Set<number>();
  for (const raw of cleaned) {
    const parsed = parseDollarInput(raw);
    if (!parsed.ok || parsed.cents === null || parsed.cents <= 0) {
      return { ok: false, error: `"${raw}" is not a valid amount.` };
    }
    if (parsed.cents > GIFT_CARD_MAX_VALUE_MINOR_UNITS) {
      return {
        ok: false,
        error: `"${raw}" is above the $2,000.00 ceiling.`,
      };
    }
    if (seen.has(parsed.cents)) {
      return { ok: false, error: `"${raw}" is listed more than once.` };
    }
    seen.add(parsed.cents);
  }

  return {
    ok: true,
    value: {
      presetAmountsMinorUnits: [...seen].sort((a, b) => a - b),
      customAmountEnabled: values.customAmountEnabled,
    },
  };
}

// A normalized lookup query for the "find a gift card" form.
export function normalizeGiftCardQuery(raw: string): string {
  return raw.trim();
}
